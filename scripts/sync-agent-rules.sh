#!/bin/bash
# Rebuilds AGENTS.md from rules/always. Strips YAML frontmatter.
# Also relinks every rule into each agent tool dir so a new rule is never missed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/AGENTS.md"
TMP="$(mktemp)"

strip_frontmatter() {
  awk '
    BEGIN { state = 0 }
    state == 0 && $0 == "---" { state = 1; next }
    state == 1 && $0 == "---" { state = 2; next }
    state == 1 { next }
    { print }
  ' "$1"
}

{
  cat <<'EOF'
# Agent rules

Edit the files in `rules/always/`, then run `scripts/sync-agent-rules.sh`.
Do not edit this file by hand. Scoped rules stay in `rules/scoped/` and are not copied here.

These rules are hard. If a tool default conflicts with them, follow these rules for response style, folder boundaries, and dev state safety.

EOF
  for file in "$ROOT"/rules/always/*.md; do
    strip_frontmatter "$file"
    printf '\n'
  done
} > "$TMP"

mv "$TMP" "$OUT"
printf 'Wrote %s\n' "$OUT"

# Agent tool dirs. Every rule file is linked with a path relative to the repo root.
DIRS=(".qoder/rules:.md" ".cursor/rules:.mdc" ".agents/rules:.md")

for entry in "${DIRS[@]}"; do
  dir="${entry%%:*}"
  ext="${entry##*:}"
  mkdir -p "$ROOT/$dir"
  for group in always scoped; do
    for file in "$ROOT/rules/$group"/*.md; do
      [[ -e "$file" ]] || continue
      name="$(basename "$file")"
      link="$ROOT/$dir/${name%.md}$ext"
      if [[ -e "$link" && ! -L "$link" ]]; then
        printf 'Skip %s: real file, not a link\n' "$dir/${name%.md}$ext"
        continue
      fi
      ln -sfn "../../rules/$group/$name" "$link"
    done
  done
done
printf 'Relinked rules into .qoder/rules, .cursor/rules, .agents/rules\n'
